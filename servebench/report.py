"""results/<experiment>/<server>_<x>.json -> results/SUMMARY.md and docs/img/*.png"""

import bisect
import json
import pathlib
import random
import statistics
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SERVERS = ["llamacpp", "lmstudio-gguf", "mlx", "lmstudio-mlx", "fake"]
COLORS = dict(zip(SERVERS, ["#1f77b4", "#7fb3e0", "#d62728", "#f0928f", "#888888"]))


def load(results: pathlib.Path) -> dict:
    """{experiment: {server: [(x, run), ...]}} sorted by x."""
    out = defaultdict(lambda: defaultdict(list))
    for f in sorted(results.glob("*/*.json")):
        run = json.loads(f.read_text())
        tags = run["config"]["tags"]
        x = tags["x"]
        try:
            x = float(x)
        except ValueError:
            pass
        run["file"] = f"{f.parent.name}/{f.name}"
        out[tags["experiment"]][run["config"]["label"]].append((x, run))
    for by_server in out.values():
        for runs in by_server.values():
            runs.sort(key=lambda r: (isinstance(r[0], str), r[0]))
    return out


SPIKE_S = 0.03  # a gap between tokens above this is a stall: over every server's p90 at 3 req/s
NEAR_S = 0.1  # "right after a stall": prefill alone takes about this long for ~268 tokens


def stall_stats(run: dict) -> dict | None:
    """Split a run's token gaps into normal steps and stalls, and check whether stalls end just
    before another request's first token, against the same stalls placed at random times."""
    reqs = [r for r in run["requests"] if not r["error"] and r["chunk_times"]]
    gaps = [(a, b) for r in reqs for a, b in zip(r["chunk_times"], r["chunk_times"][1:])]
    if not gaps:
        return None
    events = []  # overlapping stalls of different streams are one event
    for a, b in sorted(g for g in gaps if g[1] - g[0] > SPIKE_S):
        if events and a <= events[-1][1]:
            events[-1][1] = max(events[-1][1], b)
        else:
            events.append([a, b])
    firsts = [r["chunk_times"][0] for r in reqs]

    def lags(evs):  # first token minus the end of the latest stall (a stream can lag by 20 ms)
        ends = sorted(e[1] for e in evs)
        idx = (bisect.bisect_right(ends, f + 0.02) for f in firsts)
        return [f - ends[i - 1] for f, i in zip(firsts, idx) if i]

    def near(evs):
        return sum(lag <= NEAR_S for lag in lags(evs)) / len(firsts)

    rng = random.Random(0)
    start, stop = min(firsts), max(r["chunk_times"][-1] for r in reqs)
    chance = statistics.mean(
        near([[t := rng.uniform(start, stop), t + b - a] for a, b in events]) for _ in range(50))
    normal = [b - a for a, b in gaps if b - a <= SPIKE_S]
    stalled = sum(b - a for a, b in gaps if b - a > SPIKE_S)
    return {
        "itl": [b - a for a, b in gaps],
        "normal_per_gap": sum(normal) / len(gaps),
        "stall_per_gap": stalled / len(gaps),
        "stall_share": stalled / (stalled + sum(normal)),
        "events": len(events),
        "stall_s_per_request": sum(b - a for a, b in events) / len(reqs),
        "lags": lags(events),
        "near": near(events),
        "chance": chance,
    }


def labels(by_server: dict) -> list:
    """Known servers in fixed order, then variants such as llamacpp-cache-ram0."""
    return [s for s in SERVERS if s in by_server] + sorted(set(by_server) - set(SERVERS))


def color(label: str) -> str:
    """A variant (llamacpp-4b) takes its server's colour; plots draw it dashed."""
    base = [s for s in SERVERS if label == s or label.startswith(s + "-")]
    return COLORS.get(max(base, key=len, default=""), "#555555")


def grouped(runs: list) -> list:
    """[(x, [run, ...])] in x order: repeats of one point share x."""
    out = {}
    for x, run in runs:
        out.setdefault(x, []).append(run)
    return list(out.items())


def spread(runs: list) -> str:
    """min–max of TTFT p50 (ms) and output tok/s over the repeats of one point."""
    ok = [r["summary"] for r in runs if r["summary"]["n_ok"]]
    if len(ok) < 2:
        return "–"
    t = [s["ttft_s"]["p50"] for s in ok]
    v = [s["output_tok_per_s"] for s in ok]
    return f"{len(ok)} reps: {ms(min(t))}–{ms(max(t))} · {min(v):.0f}–{max(v):.0f}"


def ms(v):
    return "–" if v is None else f"{v * 1e3:.0f}" if v >= 0.1 else f"{v * 1e3:.1f}"


def table(data: dict) -> str:
    lines = ["# Summary of every run", "",
             "Generated by `servebench report` from the JSON files next to it. Times in ms.",
             "Repeats of one point (`_rep<N>` files) share x; the spread column is min–max over them.",
             "GPU % before = other apps' GPU use sampled just before the run; above ~15% the",
             "run shared the GPU with something else (usually a Blender render).", ""]
    head = ("| server | x | ok/n | prompt tok | cached tok | out tok | TTFT p50 | TTFT p99 | TPOT p50 "
            "| TPOT p99 | out tok/s | goodput req/s | SLO % | load before→after | GPU % before "
            "| spread: TTFT p50 · tok/s | server prompt ms | file |")
    for exp, by_server in sorted(data.items()):
        lines += [f"## {exp}", "", head, "|" + "---|" * (head.count("|") - 1)]
        for server in labels(by_server):
            for x, runs in grouped(by_server[server]):
                for run in runs:
                    s = run["summary"]
                    lb, la = run["state_before"]["loadavg"][0], run["state_after"]["loadavg"][0]
                    f = run["file"]
                    gpu = run["state_before"].get("gpu_util_pct")
                    if not s["n_ok"]:
                        lines.append(f"| {server} | {x:g} | 0/{s['n']} | failed: {s['errors']} |")
                        continue
                    pt, ct = s["mean_prompt_tokens"], s.get("mean_cached_tokens")
                    sp = s.get("mean_server_prompt_ms")
                    lines.append(
                        f"| {server} | {x if isinstance(x, str) else f'{x:g}'} | {s['n_ok']}/{s['n']} "
                        f"| {pt:.0f} | {'–' if ct is None else f'{ct:.0f}'} | {s['mean_output_tokens']:.0f} "
                        f"| {ms(s['ttft_s']['p50'])} | {ms(s['ttft_s']['p99'])} | {ms(s['tpot_s']['p50'])} "
                        f"| {ms(s['tpot_s']['p99'])} | {s['output_tok_per_s']:.0f} "
                        f"| {s['goodput_req_per_s']:.2f} | {100 * s['slo_attainment']:.0f} "
                        f"| {lb:.1f}→{la:.1f} | {'–' if gpu is None else f'{gpu:.0f}'} | {spread(runs)} "
                        f"| {'–' if sp is None else ms(sp / 1e3)} | `{f}` |")
        lines.append("")
    lines += stall_table(data)
    return "\n".join(lines)


def stall_runs(data: dict) -> list:
    """Open-loop rates up to 4 req/s, and the closed-loop run with 8 users as the control.
    First repeat only."""
    def first(runs):
        return [(x, r) for x, r in runs if r["config"]["tags"].get("rep", "1") == "1"]
    out = []
    for server in SERVERS:
        rate = first(data.get("rate", {}).get(server, []))
        c8 = first(data.get("concurrency", {}).get(server, []))
        out += [(f"{server} r{x:g}", server, r) for x, r in rate if x <= 4]
        out += [(f"{server} c8", server, r) for x, r in c8 if x == 8]
    return out


def stall_table(data: dict) -> list[str]:
    rows = [(name, r, stall_stats(r)) for name, _, r in stall_runs(data)]
    head = ("| run | TPOT p50 | mean token gap | from gaps ≤ 30 ms | from gaps > 30 ms | stall share % | stalls "
            "| stall ms per request | first tokens ≤ 100 ms after a stall % | same, stalls at random times % | file |")
    lines = ["## stalls", "",
             "Token gaps above 30 ms in the open-loop runs and in the closed-loop control (c8).",
             "Mean token gap = the two columns after it. Times in ms.", "",
             head, "|" + "---|" * (head.count("|") - 1)]
    for name, r, s in rows:
        if s:
            lines.append(
                f"| {name} | {r['summary']['tpot_s']['p50'] * 1e3:.1f} "
                f"| {(s['normal_per_gap'] + s['stall_per_gap']) * 1e3:.1f} "
                f"| {s['normal_per_gap'] * 1e3:.1f} | {s['stall_per_gap'] * 1e3:.1f} "
                f"| {100 * s['stall_share']:.0f} | {s['events']} | {s['stall_s_per_request'] * 1e3:.0f} "
                f"| {100 * s['near']:.0f} | {100 * s['chance']:.0f} | `{r['file']}` |")
    return lines + [""]


def _lines(ax, by_server, metric, title, ylabel, logx=False, p99=False):
    """Median over repeats; a band from min to max where a point has more than one run."""
    variants = [s for s in labels(by_server) if s not in SERVERS]
    for server in labels(by_server):
        pts = [(x, [r["summary"] for r in rs if r["summary"]["n_ok"]])
               for x, rs in grouped(by_server[server])]
        pts = [(x, ss) for x, ss in pts if ss]
        xs = [x for x, _ in pts]
        p50 = [[metric(s, "p50") for s in ss] for _, ss in pts]
        ax.plot(xs, [statistics.median(v) for v in p50], "o-" if server in SERVERS else "sv^DP<>"[variants.index(server) % 7] + "--",
                color=color(server), label=server + (" p50" if p99 else ""))
        if any(len(v) > 1 for v in p50):
            ax.fill_between(xs, [min(v) for v in p50], [max(v) for v in p50],
                            color=color(server), alpha=0.2, lw=0)
        if p99:
            ax.plot(xs, [statistics.median(metric(s, "p99") for s in ss) for _, ss in pts], "x--",
                    color=color(server), alpha=0.7, label=server + " p99")
    if logx:
        ax.set_xscale("log", base=2)
        ax.set_xticks(xs, [f"{x:g}" for x in xs])
    ax.set_title(title)
    ax.set_ylabel(ylabel)
    ax.grid(alpha=0.3)


def plots(data: dict, out: pathlib.Path):
    out.mkdir(parents=True, exist_ok=True)
    figs = []

    if d := data.get("concurrency"):
        fig, ax = plt.subplots(1, 3, figsize=(16, 4.5))
        _lines(ax[0], d, lambda s, p: s["ttft_s"][p] * 1e3, "TTFT vs concurrency", "ms", True, True)
        _lines(ax[1], d, lambda s, p: s["tpot_s"][p] * 1e3, "TPOT vs concurrency", "ms", True)
        _lines(ax[2], d, lambda s, p: s["output_tok_per_s"], "Output throughput", "tokens/s", True)
        ax[0].set_yscale("log")
        for a in ax:
            a.set_xlabel("concurrent users (closed loop)")
        ax[0].legend(fontsize=7)
        figs.append((fig, "concurrency.png"))

    if d := data.get("rate"):
        fig, ax = plt.subplots(1, 2, figsize=(11, 4.5))
        _lines(ax[0], d, lambda s, p: s["goodput_req_per_s"], "Goodput (TTFT≤1s, TPOT≤50ms)", "req/s")
        lim = max(x for runs in d.values() for x, _ in runs)
        ax[0].plot([0, lim], [0, lim], ":", color="grey", label="offered rate")
        _lines(ax[1], d, lambda s, p: s["ttft_s"][p] * 1e3, "TTFT vs offered rate", "ms", p99=True)
        ax[1].set_yscale("log")
        for a in ax:
            a.set_xlabel("offered rate, req/s (Poisson)")
            a.legend(fontsize=7)
        figs.append((fig, "rate.png"))

    if d := data.get("arrivals"):
        fig, ax = plt.subplots(figsize=(8, 4.5))
        servers = labels(d)
        patterns = [x for x, _ in grouped(d[servers[0]])]
        w = 0.8 / len(servers)
        for i, server in enumerate(servers):
            runs = dict(grouped(d[server]))
            pos = [j + i * w for j in range(len(patterns))]

            def ttft(p, q):
                return [r["summary"]["ttft_s"][q] * 1e3 for r in runs[p]]
            ax.bar(pos, [statistics.median(ttft(p, "p99")) for p in patterns], w,
                   color=color(server), alpha=0.45)
            mid = [statistics.median(ttft(p, "p50")) for p in patterns]
            err = [[m - min(ttft(p, "p50")) for m, p in zip(mid, patterns)],
                   [max(ttft(p, "p50")) - m for m, p in zip(mid, patterns)]]
            ax.bar(pos, mid, w, color=color(server), label=server,
                   yerr=err if any(len(runs[p]) > 1 for p in patterns) else None, capsize=2)
        ax.set_xticks([j + w * (len(servers) - 1) / 2 for j in range(len(patterns))], patterns)
        ax.set_ylabel("TTFT ms (solid p50, pale p99)")
        ax.set_title("Same mean rate (2 req/s), different arrival patterns")
        ax.legend(fontsize=7)
        ax.grid(alpha=0.3, axis="y")
        figs.append((fig, "arrivals.png"))

    if d := data.get("prompt"):
        fig, ax = plt.subplots(1, 2, figsize=(11, 4.5))
        _lines(ax[0], d, lambda s, p: s["ttft_s"][p] * 1e3, "TTFT vs prompt length (1 user)", "ms")
        _lines(ax[1], d, lambda s, p: s["tpot_s"][p] * 1e3, "TPOT vs prompt length (1 user)", "ms")
        for a in ax:
            a.set_xlabel("prompt words (~tokens)")
            a.legend(fontsize=7)
        figs.append((fig, "prompt.png"))

    if d := data.get("prefix"):
        fig, ax = plt.subplots(figsize=(7, 4.5))
        _lines(ax, d, lambda s, p: s["ttft_s"][p] * 1e3,
               "TTFT p50, 2048-token prompts, 4 users", "ms")
        ax.set_xlabel("tokens shared by all prompts")
        ax.legend(fontsize=7)
        figs.append((fig, "prefix.png"))

    r3 = [(n, sv, r) for n, sv, r in stall_runs(data) if n.endswith(" r3")]
    c8 = [(n, sv, r) for n, sv, r in stall_runs(data) if n.endswith(" c8")]
    if r3 and c8:
        fig, ax = plt.subplots(1, 3, figsize=(16, 4.5))
        for runs, style in ((r3, "-"), (c8, ":")):
            for name, server, r in runs:
                itl = sorted(stall_stats(r)["itl"])
                ax[0].step([v * 1e3 for v in itl], [(i + 1) / len(itl) for i in range(len(itl))],
                           style, color=color(server), label=name)
        ax[0].axvline(SPIKE_S * 1e3, color="grey", lw=0.8)
        ax[0].set_xscale("log")
        ax[0].set_title("Token gaps: 3 req/s (solid), 8 users (dotted)")
        ax[0].set_xlabel("gap between tokens, ms (grey: stall threshold)")
        ax[0].set_ylabel("share of gaps")
        ax[0].legend(fontsize=7)
        names = [n for n, _, _ in r3 + c8]
        st = [stall_stats(r) for _, _, r in r3 + c8]
        normal = [s["normal_per_gap"] * 1e3 for s in st]
        ax[1].bar(names, normal, color=[color(sv) for _, sv, _ in r3 + c8], label="gaps ≤ 30 ms")
        ax[1].bar(names, [s["stall_per_gap"] * 1e3 for s in st], bottom=normal, color="#444444",
                  label="gaps > 30 ms")
        ax[1].tick_params(axis="x", rotation=40, labelsize=7)
        ax[1].set_title("What the mean token gap is made of")
        ax[1].set_ylabel("ms")
        ax[1].legend(fontsize=7)
        for name, server, r in r3:
            ax[2].hist([v * 1e3 for v in stall_stats(r)["lags"]], bins=range(-20, 201, 10),
                       histtype="step", color=color(server), label=name)
        ax[2].set_title("First tokens by time since the latest stall ended, 3 req/s")
        ax[2].set_xlabel("ms")
        ax[2].set_ylabel("requests")
        ax[2].legend(fontsize=7)
        figs.append((fig, "stalls.png"))

    for fig, name in figs:
        fig.tight_layout()
        fig.savefig(out / name, dpi=110)
        plt.close(fig)
    return [n for _, n in figs]


def report(results: pathlib.Path, img: pathlib.Path):
    data = load(results)
    (results / "SUMMARY.md").write_text(table(data))
    return plots(data, img)
